"""Proposal builder — formats scope of work into a professional proposal."""

from task3_meeting_scope.scope_generator import ScopeOfWork


class ProposalBuilder:
    """Generates a formatted proposal from a scope of work."""

    def build(self, scope: ScopeOfWork) -> str:
        """Build a Markdown-formatted proposal document."""
        sections = [
            self._header(scope),
            self._executive_summary(scope),
            self._requirements_table(scope),
            self._hours_breakdown(scope),
            self._feasibility_report(scope),
            self._assumptions(scope),
            self._out_of_scope(scope),
            self._risks(scope),
            self._footer(),
        ]
        return "\n\n".join(sections)

    def _header(self, scope: ScopeOfWork) -> str:
        return f"""# Project Proposal: {scope.meeting_title}

**Prepared by:** AI Tech Consultant
**Total Estimated Hours:** {scope.total_hours}
**Requirements Count:** {len(scope.requirements)}"""

    def _executive_summary(self, scope: ScopeOfWork) -> str:
        must_haves = [r for r in scope.requirements if r.priority == "must_have"]
        should_haves = [r for r in scope.requirements if r.priority == "should_have"]
        nice_to_haves = [r for r in scope.requirements if r.priority == "nice_to_have"]

        return f"""## Executive Summary

This proposal outlines **{len(scope.requirements)}** requirements identified during the meeting:
- **Must Have:** {len(must_haves)} items ({sum(r.estimated_hours for r in must_haves):.0f} hours)
- **Should Have:** {len(should_haves)} items ({sum(r.estimated_hours for r in should_haves):.0f} hours)
- **Nice to Have:** {len(nice_to_haves)} items ({sum(r.estimated_hours for r in nice_to_haves):.0f} hours)"""

    def _requirements_table(self, scope: ScopeOfWork) -> str:
        rows = ["## Requirements\n"]
        rows.append("| ID | Title | Priority | Hours | Feasibility |")
        rows.append("|---|---|---|---|---|")

        for req in scope.requirements:
            rows.append(
                f"| {req.id} | {req.title} | {req.priority} | "
                f"{req.estimated_hours:.0f} | {req.feasibility} |"
            )

        return "\n".join(rows)

    def _hours_breakdown(self, scope: ScopeOfWork) -> str:
        lines = ["## Hours Breakdown\n"]
        for req in scope.requirements:
            lines.append(f"- **{req.id}: {req.title}** — {req.estimated_hours:.0f} hours")
            lines.append(f"  {req.description[:150]}")

        lines.append(f"\n**Total: {scope.total_hours:.0f} hours**")
        return "\n".join(lines)

    def _feasibility_report(self, scope: ScopeOfWork) -> str:
        lines = ["## Feasibility Report\n"]
        for req in scope.requirements:
            icon = {"feasible": "✅", "needs_research": "🔍", "not_feasible": "❌"}.get(
                req.feasibility, "❓"
            )
            lines.append(f"### {icon} {req.id}: {req.title}")
            lines.append(f"**Status:** {req.feasibility}")
            if req.feasibility_notes:
                lines.append(f"**Notes:** {req.feasibility_notes[:200]}")
            lines.append("")

        return "\n".join(lines)

    def _assumptions(self, scope: ScopeOfWork) -> str:
        if not scope.assumptions:
            return "## Assumptions\n\n_None identified._"

        items = "\n".join(f"- {a}" for a in scope.assumptions)
        return f"## Assumptions\n\n{items}"

    def _out_of_scope(self, scope: ScopeOfWork) -> str:
        if not scope.out_of_scope:
            return "## Out of Scope\n\n_Nothing explicitly excluded._"

        items = "\n".join(f"- {a}" for a in scope.out_of_scope)
        return f"## Out of Scope\n\n{items}"

    def _risks(self, scope: ScopeOfWork) -> str:
        if not scope.risks:
            return "## Risks\n\n_No significant risks identified._"

        items = "\n".join(f"- ⚠️ {r}" for r in scope.risks)
        return f"## Risks\n\n{items}"

    def _footer(self) -> str:
        return """---

*This proposal was generated by the AI Tech Consultant system.
All estimates are preliminary and subject to refinement after detailed analysis.*"""
